const DICTS: Record<Lang, Dict> = { ja, en, fr, zh, ko };

/** その言語の言葉を引く道具を作る。未訳があれば日本語で出す */
export function translator(lang: Lang): (key: Key) => string {
  const dict = DICTS[lang] ?? ja;
  return (key) => dict[key] ?? ja[key] ?? key;
}

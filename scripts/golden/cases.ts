export interface GoldenCase {
  /** ファイル名に使う番号つきの名前（半角） */
  id: string;
  /** 何を確かめる見本か（画面の一覧に出す） */
  title: string;
  answers: Answers;
  /**
   * 図面に必ず入っているべき記号。「pas」なら、名前の頭が pas の記号が1つ以上。
   * 「tr-3p-dy=5」のように「=」を付けると、その記号がちょうど5個。
   */
  mustHave: string[];
  /** 図面に入っていてはいけない記号（名前の頭が合うもの） */
  mustNot?: string[];
  /** レイヤーの見本のとき：図面の上に赤い印を置いて、そのレイヤーの印刷を見本にする（scripts/golden/layers.ts） */
  layer?: LayerStep;
}

